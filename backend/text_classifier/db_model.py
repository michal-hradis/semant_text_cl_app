from __future__ import annotations

import enum
import uuid
from datetime import datetime

from sqlalchemy import Boolean, DateTime, Enum, Float, ForeignKey, Integer, String, Text as SQLText, UniqueConstraint
from sqlalchemy.dialects.sqlite import JSON
from sqlalchemy.orm import Mapped, mapped_column

from text_classifier.database import Base
import random


class AnnotationType(str, enum.Enum):
    user = "user"
    ground_truth = "ground_truth"
    llm = "llm"


class Task(Base):
    __tablename__ = "tasks"

    id: Mapped[str] = mapped_column(String, primary_key=True)
    name: Mapped[str] = mapped_column(String, nullable=False)
    description_md: Mapped[str] = mapped_column(SQLText, nullable=False)
    multi_choice: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    max_choices: Mapped[int] = mapped_column(default=1, nullable=False)
    enabled: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    classes: Mapped[list[dict]] = mapped_column(JSON, nullable=False)
    # Sampling configuration
    calib_ratio_initial: Mapped[float] = mapped_column(Float, default=0.30, nullable=False, server_default='0.3')
    calib_initial_count: Mapped[int] = mapped_column(Integer, default=20, nullable=False, server_default='20')
    calib_ratio_ongoing: Mapped[float] = mapped_column(Float, default=0.10, nullable=False, server_default='0.1')
    repeat_probability: Mapped[float] = mapped_column(Float, default=0.20, nullable=False, server_default='0.2')
    target_coverage: Mapped[int] = mapped_column(Integer, default=3, nullable=False, server_default='3')


class TextItem(Base):
    __tablename__ = "texts"

    id: Mapped[str] = mapped_column(String, primary_key=True)
    text: Mapped[str] = mapped_column(SQLText, nullable=False)
    language: Mapped[str] = mapped_column(String, nullable=False)
    raw_json: Mapped[dict] = mapped_column(JSON, nullable=False)
    suspended: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False, server_default='0')
    random_order: Mapped[float] = mapped_column(Float, default=random.random, nullable=False, index=True)


class Annotation(Base):
    __tablename__ = "annotations"
    # Single person can annotate single text multiple times - this is not a problem.
    #__table_args__ = (UniqueConstraint("user_id", "text_id", "task_id", "annotation_type", name="uq_annotation_user_text_task_type"),)

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("user.id"), nullable=False)
    text_id: Mapped[str] = mapped_column(ForeignKey("texts.id"), nullable=False)
    task_id: Mapped[str] = mapped_column(ForeignKey("tasks.id"), nullable=False)
    selected_classes: Mapped[list[str]] = mapped_column(JSON, nullable=False)
    start_time: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    end_time: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, nullable=False)
    annotation_type: Mapped[AnnotationType] = mapped_column(
        Enum(AnnotationType, native_enum=False),
        default=AnnotationType.user,
        nullable=False,
        server_default=AnnotationType.user.value,
    )
    weight: Mapped[float] = mapped_column(Float, default=1.0, nullable=False, server_default='1.0')
    points_earned: Mapped[float | None] = mapped_column(Float, nullable=True, default=None)


class UserReliability(Base):
    __tablename__ = "user_reliability"
    __table_args__ = (UniqueConstraint("user_id", "task_id", name="uq_reliability_user_task"),)

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("user.id"), nullable=False)
    task_id: Mapped[str] = mapped_column(ForeignKey("tasks.id"), nullable=False)
    pairwise_agreement: Mapped[float | None] = mapped_column(Float, nullable=True)
    cohens_kappa: Mapped[float | None] = mapped_column(Float, nullable=True)
    krippendorffs_alpha: Mapped[float | None] = mapped_column(Float, nullable=True)
    ds_sensitivity: Mapped[float | None] = mapped_column(Float, nullable=True)
    annotation_count: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    computed_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)


class AnnotationSession(Base):
    """One text shown to one annotator, from display to submit (see docs/voice_comments.md).

    Holds the interaction events of the submit and the IDs of the annotations it created.
    The ID is generated by the client when the text is shown.
    """
    __tablename__ = "annotation_sessions"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("user.id"), nullable=False, index=True)
    text_id: Mapped[str] = mapped_column(ForeignKey("texts.id"), nullable=False, index=True)
    task_ids: Mapped[list[str]] = mapped_column(JSON, nullable=False)
    annotation_ids: Mapped[list[str]] = mapped_column(JSON, nullable=False)
    # Client wall-clock time when the text was shown; event offsets (t_ms) are relative to it.
    client_started_at: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    # JSON list of {type, t_ms, task_id?, class_id?}
    events: Mapped[list[dict]] = mapped_column(JSON, nullable=False)
    submitted_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, nullable=False)


class TranscriptionStatus(str, enum.Enum):
    pending = "pending"
    done = "done"
    failed = "failed"


class VoiceComment(Base):
    """Audio recording of an annotator thinking aloud during one annotation session."""
    __tablename__ = "voice_comments"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    session_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("annotation_sessions.id"), nullable=False, unique=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("user.id"), nullable=False)
    text_id: Mapped[str] = mapped_column(ForeignKey("texts.id"), nullable=False, index=True)
    language: Mapped[str] = mapped_column(String, nullable=False)
    # Path relative to VOICE_AUDIO_PATH
    file_path: Mapped[str] = mapped_column(String, nullable=False)
    mime_type: Mapped[str] = mapped_column(String, nullable=False)
    size_bytes: Mapped[int] = mapped_column(Integer, nullable=False)
    # Recording start/end in ms relative to AnnotationSession.client_started_at
    start_ms: Mapped[int] = mapped_column(Integer, nullable=False)
    end_ms: Mapped[int] = mapped_column(Integer, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, nullable=False)
    transcription_status: Mapped[TranscriptionStatus] = mapped_column(
        Enum(TranscriptionStatus, native_enum=False),
        default=TranscriptionStatus.pending,
        nullable=False,
        index=True,
    )
    transcription_attempts: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    transcription_error: Mapped[str | None] = mapped_column(SQLText, nullable=True)
    transcription_model: Mapped[str | None] = mapped_column(String, nullable=True)
    transcript: Mapped[str | None] = mapped_column(SQLText, nullable=True)
    # JSON list of {start, end, text} in seconds from recording start; only if the model returns segments
    transcript_segments: Mapped[list[dict] | None] = mapped_column(JSON, nullable=True)
    transcribed_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
